/**
 * Unit test for lib/maintenance.js — reference collection (live + persisted)
 * and orphan pruning, against temporary directories so nothing real is ever
 * touched. The persisted-corpus path uses a real zstd-compressed JSONL log
 * (node:zlib built-in), mirroring the platform's session layout.
 */

import { mkdtemp, mkdir, readdir, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { zstdCompressSync, zstdDecompressSync } from 'node:zlib'
import { cleanupOrphans, collectFromValue, collectPersistedReferences, decodeSessionLog, emptyReferences, encodeSessionLog, scanZstdFrames, storageStats } from './lib/maintenance.js'

let failures = 0
const check = (label, ok) => {
  if (ok) console.log(`  ok  ${label}`)
  else { failures += 1; console.log(`FAIL  ${label}`) }
}

// --- collectFromValue -------------------------------------------------------

{
  const refs = emptyReferences()
  collectFromValue({
    data: {
      message: {
        content: [
          { type: 'text', text: 'hello' },
          { type: 'uploaded-image', path: 'C:\\u\\uploads\\a.png', attachment: { attachmentId: 'aaa' } },
          { type: 'generated-image', attachment: { attachmentId: 'bbb' } },
          { type: 'image', attachment: { attachmentId: 'ccc' } },
          { type: 'tool-result', content: [{ type: 'uploaded-image', path: 'C:\\u\\uploads\\b.png', attachment: { attachmentId: 'ddd' } }] },
        ],
      },
    },
  }, refs)
  check('collectFromValue picks uploaded-image paths (incl. nested tool-result)', refs.paths.size === 2 && refs.paths.has(resolve('C:\\u\\uploads\\a.png')))
  check('collectFromValue picks all attachment ids', refs.ids.size === 4 && refs.ids.has('aaa') && refs.ids.has('ccc'))

  // generated-image blocks carry the work-dir path of the generated bytes
  // (the model's direct edit handle) — the scan must collect it too, or the
  // cleanup would prune a live session's reference.
  const genRefs = emptyReferences()
  collectFromValue({
    data: { message: { content: [
      { type: 'generated-image', path: 'C:\\u\\uploads\\gen.png', attachment: { attachmentId: 'eee' } },
      { type: 'generated-image', attachment: { attachmentId: 'fff' } }, // no path: fine
    ] } },
  }, genRefs)
  check('collectFromValue picks generated-image work-dir paths', genRefs.paths.has(resolve('C:\\u\\uploads\\gen.png')) && genRefs.ids.has('fff'))
}

// --- temp corpus layout -----------------------------------------------------

const root = await mkdtemp(join(tmpdir(), 'imagegen-maint-'))
const uploadDir = join(root, 'uploads')
const attachmentsDir = join(root, 'attachments', 'v1')
const sessionsDir = join(root, 'sessions')
await mkdir(uploadDir, { recursive: true })
await mkdir(join(attachmentsDir, 'objects', '11'), { recursive: true })
await mkdir(join(attachmentsDir, 'objects', '22'), { recursive: true })

// Two upload files: one referenced by a persisted session, one orphan.
await writeFile(join(uploadDir, 'keep-me.png'), Buffer.alloc(10, 1))
await writeFile(join(uploadDir, 'orphan.png'), Buffer.alloc(20, 2))
// Attachment objects: one referenced, one orphan (content-addressed names).
await writeFile(join(attachmentsDir, 'objects', '11', '1111'), Buffer.alloc(30, 3))
await writeFile(join(attachmentsDir, 'objects', '22', '2222'), Buffer.alloc(40, 4))

// Persisted session log (zstd), referencing keep-me.png + 1111.
const project = join(sessionsDir, '--test-project--')
const sessionDir = join(project, 'session-1234')
await mkdir(sessionDir, { recursive: true })
const records = [
  { data: { message: { content: [
    { type: 'uploaded-image', path: join(uploadDir, 'keep-me.png'), attachment: { attachmentId: '1111' } },
    { type: 'generated-image', attachment: { attachmentId: '1111' } }, // shared object
  ] } } },
]
await writeFile(join(sessionDir, 'session.jsonl.zstd'), zstdCompressSync(records.map((r) => JSON.stringify(r)).join('\n')))
// A corrupt log must be skipped, not fatal.
const corruptDir = join(project, 'session-corrupt')
await mkdir(corruptDir, { recursive: true })
await writeFile(join(corruptDir, 'session.jsonl.zstd'), 'not zstd at all')

// Live session referencing a THIRD upload not in any persisted log, plus a
// generated-image block whose work-dir copy must also survive pruning.
const stubSessions = {
  list() {
    return [{
      events: [{
        data: { message: { content: [
          { type: 'uploaded-image', path: join(uploadDir, 'live.png'), attachment: { attachmentId: '3333' } },
          { type: 'generated-image', path: join(uploadDir, 'gen.png'), attachment: { attachmentId: '4444' } },
        ] } },
      }],
    }]
  },
}
await writeFile(join(uploadDir, 'live.png'), Buffer.alloc(50, 5))
await writeFile(join(uploadDir, 'gen.png'), Buffer.alloc(70, 7))
await mkdir(join(attachmentsDir, 'objects', '44'), { recursive: true })
await writeFile(join(attachmentsDir, 'objects', '44', '4444'), Buffer.alloc(80, 8))
await mkdir(join(attachmentsDir, 'objects', '33'), { recursive: true })
await writeFile(join(attachmentsDir, 'objects', '33', '3333'), Buffer.alloc(60, 6))

// --- collectPersistedReferences --------------------------------------------

{
  const refs = emptyReferences()
  await collectPersistedReferences(sessionsDir, refs)
  check('persisted log refs collected (zstd decoded)', refs.paths.has(join(uploadDir, 'keep-me.png')) && refs.ids.has('1111'))
  check('corrupt log skipped without throwing', refs.ids.has('1111'))
}

// --- stats ------------------------------------------------------------------

{
  const stats = await storageStats({ uploadsRoot: uploadDir, attachmentsRoot: attachmentsDir })
  check('stats count uploads + objects', stats.uploads.count === 4 && stats.attachments.count === 4)
  check('stats sum bytes', stats.uploads.bytes === 150 && stats.attachments.bytes === 210)
}

// --- cleanupOrphans ---------------------------------------------------------

{
  const result = await cleanupOrphans(stubSessions, {
    sessionsRoot: sessionsDir,
    uploadsRoot: uploadDir,
    attachmentsRoot: attachmentsDir,
  })
  check('cleanup removed only the orphan upload', result.uploads.removed === 1 && result.uploads.bytesFreed === 20)
  check('cleanup removed only the orphan object', result.attachments.removed === 1 && result.attachments.bytesFreed === 40)
  const uploads = await readdir(uploadDir)
  check('referenced + live uploads survive (incl. generated-image path)', uploads.includes('keep-me.png') && uploads.includes('live.png') && uploads.includes('gen.png') && !uploads.includes('orphan.png'))
  const objects = (await readdir(join(attachmentsDir, 'objects', '11'))).concat(
    await readdir(join(attachmentsDir, 'objects', '22')),
    await readdir(join(attachmentsDir, 'objects', '33')),
    await readdir(join(attachmentsDir, 'objects', '44')),
  )
  check('referenced + live objects survive', objects.includes('1111') && objects.includes('3333') && objects.includes('4444') && !objects.includes('2222'))
}

// --- multi-frame zstd logs (rc.7 append-style) --------------------------------

{
  const frames = await mkdtemp(join(tmpdir(), 'imagegen-frames-'))
  const uploadDir = join(frames, 'uploads')
  const attachmentsDir = join(frames, 'attachments', 'v1')
  const sessionsDir = join(frames, 'sessions')
  await mkdir(uploadDir, { recursive: true })
  await mkdir(join(attachmentsDir, 'objects', 'aa'), { recursive: true })
  const sessionDir = join(sessionsDir, '--proj--', 'session-9')
  await mkdir(sessionDir, { recursive: true })

  // Frame 1: session header only. Frame 2: a reference. Frame 3: another.
  const frame1 = JSON.stringify({ type: 'session', id: 's' }) + '\n'
  const frame2 = JSON.stringify({
    data: { message: { content: [
      { type: 'generated-image', attachment: { attachmentId: 'sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa' } },
    ] } },
  }) + '\n'
  const frame3 = JSON.stringify({
    data: { content: [
      { type: 'uploaded-image', path: join(uploadDir, 'framed.png'), attachment: { attachmentId: 'bbbb' } },
    ] },
  }) + '\n'
  const log = encodeSessionLog([frame1, frame2, frame3])
  await writeFile(join(sessionDir, 'session.jsonl.zstd'), log)

  // Sanity: the container really is multi-frame, and a whole-buffer decompress
  // would only see the first frame (the exact regression this test guards).
  const { frames: ranges } = scanZstdFrames(log)
  check('encodeSessionLog produces a multi-frame container', ranges.length === 3)
  check('naive whole-buffer decompress misses later frames', zstdDecompressSync(log).toString('utf8').split('\n').filter(Boolean).length === 1)
  const { text, torn } = decodeSessionLog(log)
  check('decodeSessionLog yields every frame', !torn && text.split('\n').filter(Boolean).length === 3)

  await writeFile(join(uploadDir, 'framed.png'), Buffer.alloc(10, 1))
  await writeFile(join(attachmentsDir, 'objects', 'aa', 'aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa'), Buffer.alloc(20, 2))
  await writeFile(join(attachmentsDir, 'objects', 'aa', 'bbbb'), Buffer.alloc(30, 3))

  const refs = emptyReferences()
  await collectPersistedReferences(sessionsDir, refs)
  check('multi-frame refs collected across all frames', refs.paths.has(join(uploadDir, 'framed.png')) && refs.ids.has('sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa'))

  const result = await cleanupOrphans({ list: () => [] }, {
    sessionsRoot: sessionsDir,
    uploadsRoot: uploadDir,
    attachmentsRoot: attachmentsDir,
  })
  check('prefixed attachmentId protects its bare-hex object', result.attachments.removed === 0)
  check('framed upload survives (referenced from frame 3)', result.uploads.removed === 0)
  const survivors = await readdir(join(attachmentsDir, 'objects', 'aa'))
  check('both prefixed-referenced objects survive', survivors.length === 2)

  await rm(frames, { recursive: true, force: true })
}

await rm(root, { recursive: true, force: true })

console.log('')
if (failures > 0) {
  console.error(`MAINTENANCE FAILED: ${failures} failure(s)`)
  process.exit(1)
}
console.log('MAINTENANCE PASSED')
